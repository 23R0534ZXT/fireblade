"""Render docs/host/HOST-PARITY.md from the parity map.

The map (`host-parity.json`) says, for every label the Qt sources expose, what the
Host edition does with it. This script turns that into the page a reader opens,
and `--check` fails when the page and the map disagree — so the document cannot
drift into a claim nobody verified.

    python scripts/host_parity_report.py           # rewrite HOST-PARITY.md
    python scripts/host_parity_report.py --check    # exit 1 when it is stale
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MAP = ROOT / "docs" / "host" / "host-parity.json"
OUT = ROOT / "docs" / "host" / "HOST-PARITY.md"


def load() -> dict:
    return json.loads(MAP.read_text(encoding="utf-8"))


def counts(entries: list[dict]) -> dict:
    result: dict[str, int] = {}
    for entry in entries:
        result[entry["status"]] = result.get(entry["status"], 0) + 1
    return result


def render(data: dict) -> str:
    entries = data["commands"]
    commands = [entry for entry in entries if entry["kind"] == "command"]
    parameters = [entry for entry in entries if entry["kind"] == "parameter"]
    containers = [entry for entry in entries if entry["kind"] == "container"]
    by_status = counts(entries)
    command_counts = counts(commands)
    covered = sorted((entry for entry in commands if entry["status"] == "covered"),
                     key=lambda entry: entry["label"].casefold())
    declared = sorted((entry for entry in commands if entry["status"] == "declared"),
                      key=lambda entry: entry["label"].casefold())
    todo = sorted((entry for entry in commands if entry["status"] == "todo"),
                  key=lambda entry: entry["label"].casefold())

    lines = [
        "# Desktop → Host parity, command by command",
        "",
        "Generated by `scripts/host_parity_report.py` from `host-parity.json`, which lists",
        "every label `scripts/parity_inventory.py` finds in the Qt sources. A command is",
        "**covered** only when the browser does it *and* a test named here exercises it;",
        "**declared** means it cannot exist behind a browser, with the reason; **todo** is",
        "real desktop work this edition does not do yet, with a plan.",
        "",
        f"- labels found in the Qt sources: **{len(entries)}**",
        f"- of them, real commands: **{len(commands)}** "
        f"({command_counts.get('covered', 0)} covered, {command_counts.get('declared', 0)} "
        f"declared out of scope, {command_counts.get('todo', 0)} to do)",
        f"- parameter values counted as commands by the inventory: **{len(parameters)}**",
        f"- menu containers and dialog captions: **{len(containers)}**",
        "",
        "A line of this page is the claim; the test named beside it is the proof.",
        "",
        "**This page counts menu commands, not features.** It is built from the labels",
        "`parity_inventory.py` reads in the Qt sources, which misses whole screens opened",
        "by a button or a dialog. For the feature-level comparison, including what is",
        "still missing, read `HOST-AUDIT.md`.",
        "",
        "## Covered, with the test that proves it",
        "",
        "| command | where in the browser | test |",
        "| --- | --- | --- |",
    ]
    for entry in covered:
        lines.append(f"| {entry['label']} | {entry['where']} | `{entry['test']}` |")
    lines += [
        "",
        "## Out of scope in a browser, and why",
        "",
        "| command | why not |",
        "| --- | --- |",
    ]
    for entry in declared:
        lines.append(f"| {entry['label']} | {entry['reason']} |")
    lines += [
        "",
        "## Real work left",
        "",
    ]
    if todo:
        for entry in todo:
            lines.append(f"- **{entry['label']}** — {entry['plan']}")
    else:
        lines.append("Nothing: every desktop command is covered or declared.")
    lines += [
        "",
        "## What the inventory counts as a command",
        "",
        "The raw list carries parameter values (`append`, `remove`, `top`, `dark`…) and",
        "menu containers (`&Fichier`, `&Affichage`). They are listed in the map with the",
        "kind `parameter` or `container`, so the count above is honest: those are not",
        "commands, and marking them covered would inflate the total.",
        "",
        "## Not wired on purpose",
        "",
        "The AI assistant: nothing is connected, no endpoint and no key. The detection tab",
        "says so. The decision (local model in the container, or a remote API) is the",
        "user's, and it changes what may leave the server.",
        "",
    ]
    return "\n".join(lines)


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="fail when HOST-PARITY.md is stale")
    args = parser.parse_args(argv)
    text = render(load())
    if args.check:
        current = OUT.read_text(encoding="utf-8") if OUT.is_file() else ""
        if current != text:
            print("HOST-PARITY.md is stale: run scripts/host_parity_report.py", file=sys.stderr)
            return 1
        print("HOST-PARITY.md matches the map")
        return 0
    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
