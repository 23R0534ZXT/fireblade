"""Inventory the desktop edition's commands, so parity can be counted, not claimed.

Reads the Qt sources and lists every user-reachable action exactly once: menu and
toolbar entries, context-menu entries, and the tabs the window exposes. The output
is a markdown checklist the web edition is measured against — a feature counts as
ported only when its line is ticked and a test covers it.

    python scripts/parity_inventory.py --src src/fireblade/ui --out docs/development/PARITY.md
"""

from __future__ import annotations

import argparse
import ast
import re
from collections import Counter
from pathlib import Path

ACTION_CALLS = {"addAction", "addMenu", "addTab", "addItem"}


def string_labels(node: ast.AST) -> list[str]:
    """Literal French labels an action call carries, plus translate('...') calls."""
    labels = []
    for child in ast.walk(node):
        if isinstance(child, ast.Constant) and isinstance(child.value, str):
            text = child.value.strip()
            if 2 <= len(text) <= 120 and not text.startswith(("fireblade", "Q", "%")):
                labels.append(text)
        elif isinstance(child, ast.Call) and getattr(child.func, "id", "") == "translate":
            if (
                child.args
                and isinstance(child.args[0], ast.Constant)
                and isinstance(child.args[0].value, str)
            ):
                labels.append(child.args[0].value.strip())
    return labels


def collect(paths: list[Path]) -> dict[str, list[str]]:
    found: dict[str, set[str]] = {}
    for path in paths:
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"))
        except (SyntaxError, UnicodeDecodeError):
            continue
        for node in ast.walk(tree):
            if not isinstance(node, ast.Call):
                continue
            name = getattr(node.func, "attr", "")
            if name not in ACTION_CALLS:
                continue
            for label in string_labels(node):
                if not re.search(r"[A-Za-zÀ-ÿ]", label):
                    continue
                if label in {"text", "number", "timestamp", "value", "year", "month", "day"}:
                    continue
                found.setdefault(label, set()).add(path.name)
    return {label: sorted(files) for label, files in sorted(found.items())}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--src", type=Path, default=Path("src/fireblade/ui"))
    parser.add_argument("--out", type=Path, default=Path("docs/development/PARITY.md"))
    parser.add_argument(
        "--host",
        type=Path,
        default=None,
        help="markdown file listing the labels the Host edition already covers, one per line",
    )
    args = parser.parse_args(argv)

    entries = collect(sorted(args.src.glob("*.py")))
    covered = set()
    if args.host and args.host.is_file():
        covered = {
            line.strip()
            for line in args.host.read_text(encoding="utf-8").splitlines()
            if line.strip() and not line.startswith("#")
        }

    files = Counter(name for names in entries.values() for name in names)
    lines = [
        "# Desktop → Host parity",
        "",
        "Generated by `scripts/parity_inventory.py` from the Qt sources. Every line is one",
        "user-reachable command of the desktop edition. The port is complete when every line",
        "is ticked, with a test that exercises it on the Host edition.",
        "",
        f"- commands found: **{len(entries)}**",
        f"- covered by Host: **{len([l for l in entries if l in covered])}**",
        f"- declared in: "
        + ", ".join(f"`{name}` ({count})" for name, count in files.most_common(12)),
        "",
        "| | command | declared in |",
        "| --- | --- | --- |",
    ]
    for label, names in entries.items():
        tick = "x" if label in covered else " "
        lines.append(f"| [{tick}] | {label} | {', '.join(names)} |")
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"{len(entries)} commands -> {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
