LANGUAGES = ("en", "fr")
SOURCE_LANGUAGE = "fr"
DEFAULT = "en"
NAMES = {"en": "English", "fr": "Français"}

_language = DEFAULT


def current_language():
    return _language


def fallback_language():
    """What a stored or malformed code becomes."""
    return DEFAULT


def set_language(code):
    global _language
    if code not in LANGUAGES:
        raise ValueError(f"Langue inconnue : {code!r}")
    lookup.cache_clear()
    templates.cache_clear()
    _language = code
    return _language


@lru_cache(maxsize=1)
def templates():
    """Compiled templates, the most specific literal first.

    ``"3 analyses en erreur"`` must reach its own entry, not the generic
    ``"{} en erreur"``: sorting by the length of the fixed text decides.

    Each entry carries its longest fixed piece as an *anchor*. A run-time string
    that does not contain it cannot match, and the check is a plain substring
    search: trying a hundred regular expressions on every label the interface
    writes is what made a heavy test file thirty times slower.
    """
    compiled = []
    for source, target in EN.items():
        if PLACEHOLDER not in source:
            continue
        parts = source.split(PLACEHOLDER)
        pattern = re.compile("^" + "(.+?)".join(re.escape(part) for part in parts) + "$", re.S)
        anchor = max(parts, key=len)
        compiled.append((sum(len(part) for part in parts), anchor, pattern, target))
    compiled.sort(key=lambda item: -item[0])
    return tuple(compiled)


@lru_cache(maxsize=8192)
def lookup(text):
    """English display text for a French source string, or the string itself."""
    exact = EN.get(text)
    if exact is not None:
        return exact
    for _, anchor, pattern, target in templates():
        if anchor and anchor not in text:
            continue
        match = pattern.match(text)
        if match is not None:
            result = target
            for value in match.groups():
                # The value is often a label of its own: translate it too.
                result = result.replace(PLACEHOLDER, translate(value), 1)
            return result
    return text


def english(text):
    """English display text, whatever language is on: the reference form."""
    return lookup(text)


def has_english(text):
    """True when the table knows this string, exactly or through a template."""
    return lookup(text) != text


def translate(text):
    """Display text for the current language; French is the source."""
    if _language == SOURCE_LANGUAGE or not text:
        return text
    return lookup(text)
