# The documents' own sentences: added to the table without replacing a label that is already there.
from fireblade.core.i18n_documents import DOCUMENTS as _DOCUMENTS  # noqa: E402
from fireblade.core.i18n_documents import PHRASES as _PHRASES  # noqa: E402
from fireblade.core.i18n_errors import ERRORS as _ERRORS  # noqa: E402

for _french, _english in {**_ERRORS, **_DOCUMENTS}.items():
    EN.setdefault(_french, _english)

LANGUAGES = ("en", "fr")
SOURCE_LANGUAGE = "fr"
DEFAULT = "en"
NAMES = {"en": "English", "fr": "Français"}

_language = DEFAULT


def current_language():
    return _language


def fallback_language():
    """What a stored or malformed code becomes."""
    return DEFAULT


def set_language(code):
    global _language
    if code not in LANGUAGES:
        raise ValueError(f"Langue inconnue : {code!r}")
    lookup.cache_clear()
    templates.cache_clear()
    _language = code
    return _language


@lru_cache(maxsize=1)
def templates():
    """Compiled templates, the most specific literal first.

    ``"3 analyses en erreur"`` must reach its own entry, not the generic
    ``"{} en erreur"``: sorting by the length of the fixed text decides.

    Each entry carries its longest fixed piece as an *anchor*. A run-time string
    that does not contain it cannot match, and the check is a plain substring
    search: trying a hundred regular expressions on every label the interface
    writes is what made a heavy test file thirty times slower.
    """
    compiled = []
    for source, target in EN.items():
        if PLACEHOLDER not in source:
            continue
        parts = source.split(PLACEHOLDER)
        pattern = re.compile("^" + "(.+?)".join(re.escape(part) for part in parts) + "$", re.S)
        anchor = max(parts, key=len)
        compiled.append(
            (sum(len(part) for part in parts), anchor, pattern, target, " ; " in source)
        )
    compiled.sort(key=lambda item: -item[0])
    return tuple(compiled)


@lru_cache(maxsize=8192)
def lookup(text):
    """English display text for a French source string, or the string itself."""
    exact = EN.get(text)
    if exact is not None:
        return exact
    for _, anchor, pattern, target, separated in templates():
        if anchor and anchor not in text:
            continue
        match = pattern.match(text)
        if match is not None:
            if not separated and any(" ; " in value for value in match.groups()):
                # An engine joins its reasons with " ; ": a value never spans two sentences.
                continue
            result = target
            for value in match.groups():
                # The value is often a label of its own: translate it too.
                result = result.replace(PLACEHOLDER, translate(value), 1)
            return result
    return text


def english(text):
    """English display text, whatever language is on: the reference form."""
    return lookup(text)


def english_text(text):
    """English for a sentence that also carries values: the whole text first, then its phrases.

    Reports put their values inside their sentences (``Case X · Référence client Y``), so the
    whole text can never be a key. The known phrases are replaced in place, the longest
    first, and everything else (names, dates, hashes) is left exactly as written. A template
    that matched only the front of the sentence leaves its tail to the phrases as well.
    """
    if not text:
        return text
    result = lookup(text)
    if result == text and text.strip() != text:
        inner = lookup(text.strip())
        if inner != text.strip():
            result = text[: len(text) - len(text.lstrip())] + inner + text[len(text.rstrip()) :]
    # French typography puts a no-break space before a colon: phrases are written with a plain one.
    result = result.replace("\u00a0", " ").replace("\u202f", " ")
    for phrase in sorted(_PHRASES, key=len, reverse=True):
        if phrase in result:
            result = result.replace(phrase, _PHRASES[phrase])
    if " ; " in result:
        # An engine's reasons are joined with " ; ", each one a sentence of its own, and a template
        # that ends in a value swallows the sentences that follow it: what is still unknown is read
        # again one sentence at a time.
        result = " ; ".join(lookup(part) for part in result.split(" ; "))
    return result


def has_english(text):
    """True when the table knows this string, exactly or through a template."""
    return lookup(text) != text


def translate(text):
    """Display text for the current language; French is the source."""
    if _language == SOURCE_LANGUAGE or not text:
        return text
    return lookup(text)
