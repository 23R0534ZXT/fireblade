"""The recette harness, run against the real service on the part of the test pack that needs no network.

The CatScale collection, its archive, the volume timeline and the exports are generated by
``scripts.test_pack.package`` with their expected counts; the Host imports them and the harness
compares. The Windows artifacts need the .NET readers of the image and are exercised in CI.
"""

import json
import threading
import time
from pathlib import Path

import pytest
import uvicorn

from fireblade.web.server import create_app
from scripts.recette import host_recette
from scripts.test_pack import package as pack_builder


def _build_pack(root: Path, volume_rows: int = 40) -> Path:
    from fireblade.core.catscale import parse

    pack = root / "pack"
    linux = pack / "02-Linux-CatScale"
    extracted = linux / "01-Dossier-extrait" / "node-20261102-1000"
    pack_builder.write_catscale(extracted)
    (linux / "02-Archive").mkdir()
    pack_builder.tar_directory(extracted, linux / "02-Archive/catscale_node-20261102-1000.tar.gz")
    pack_builder.write_volume(linux / "03-Volume/catscale_volume-20261102-1000.tar.gz", volume_rows)
    pack_builder.write_exports(pack / "03-Exports")
    totals, structured, raw = {}, 0, 0
    scratch = root / "scratch"
    scratch.mkdir()
    for index, path in enumerate(sorted(extracted.rglob("*"))):
        if path.is_file():
            out = scratch / str(index)
            out.mkdir()
            result = parse(path, out)
            for item in result["outputs"]:
                totals[item["family"]] = totals.get(item["family"], 0) + item["rows"]
            structured += result["structured"]
            raw += result["raw"]
    expected = dict(catscale=dict(rows=structured + raw, families=totals), volume_rows=volume_rows,
                    exports_rows=len(pack_builder.ROWS))
    (pack / "RESULTATS-ATTENDUS.json").write_text(json.dumps(expected), encoding="utf-8")
    return pack


@pytest.fixture()
def service(tmp_path):
    cases = tmp_path / "cases"
    cases.mkdir()
    port = host_recette.free_port()
    server = uvicorn.Server(uvicorn.Config(create_app(cases), host="127.0.0.1", port=port, log_level="warning"))
    thread = threading.Thread(target=server.run, daemon=True)
    thread.start()
    deadline = time.monotonic() + 15
    while not server.started and time.monotonic() < deadline:
        time.sleep(0.05)
    yield f"http://127.0.0.1:{port}"
    server.should_exit = True
    thread.join(timeout=10)


def test_the_host_accounts_for_every_file_of_each_source_and_reads_the_known_counts(tmp_path, service):
    pack = _build_pack(tmp_path)
    args = host_recette.argparse.Namespace(pack=str(pack), url=service, server_pack=str(pack), image="")
    result = host_recette.run(args)
    seen = {scenario["scenario"]: {c["name"]: c for c in scenario["checks"]} for scenario in result["scenarios"]}
    assert set(seen) == {"catscale-folder", "catscale-archive", "volume", "exports"}
    for name, checks in seen.items():
        for pinned in ("import-completes", "every-file-accounted-for", "no-file-in-error"):
            assert checks[pinned]["verdict"] == host_recette.PASS, (name, checks[pinned])
    assert seen["volume"]["volume-rows"]["verdict"] == host_recette.PASS, seen["volume"]
    assert seen["exports"]["exports-rows"]["verdict"] == host_recette.PASS, seen["exports"]
    for scenario in ("catscale-folder", "catscale-archive"):
        for name, check in seen[scenario].items():
            if name.startswith("catscale-"):
                assert check["verdict"] == host_recette.PASS, (scenario, check)
    assert host_recette.verdict(result, strict=False) == 0


def test_a_difference_is_reported_and_a_pinned_failure_fails_the_run():
    expected = {"catscale": {"rows": 10, "families": {"Persistance": 10}}}
    observed = {"files": [{"name": "a", "status": "complete"}], "statuses": {"complete": 1},
                "analyses": [{"label": "Persistence.csv", "rows": 7, "artifact": "x", "parser": ""}]}
    checks = host_recette.base_checks(observed, files_in_pack=2, job={"status": "complete"})
    checks += host_recette.check_catscale(expected, observed)
    by_name = {item.name: item for item in checks}
    assert by_name["every-file-accounted-for"].verdict == host_recette.FAIL, "one of two files has no line"
    assert by_name["catscale-Persistance"].verdict == host_recette.INFO and by_name["catscale-Persistance"].actual == 7
    failing = {"scenarios": [{"checks": [vars(item) for item in checks]}]}
    assert host_recette.verdict(failing, strict=False) == 1
    only_info = {"scenarios": [{"checks": [vars(by_name["catscale-Persistance"])]}]}
    assert host_recette.verdict(only_info, strict=False) == 0 and host_recette.verdict(only_info, strict=True) == 1
